def predict_uhi(lat, lon, ndvi, build_dens, imperv_surf, pop_density,
                model_xgb=None, model_rf=None, meta_path='uhi_meta.json'):
    """
    단일 포인트 UHI 예측 함수
    기상 데이터는 실시간으로 Open-Meteo에서 가져옴
    """
    with open(meta_path, encoding='utf-8') as f:
        meta = json.load(f)

    # 실시간 기상 수집
    w = fetch_weather(lat, lon, days_back=3)
    if w is None:
        raise ValueError('기상 데이터 수집 실패')

    X_input = np.array([[
        ndvi, build_dens, imperv_surf, pop_density,
        w['humidity'], w['windspeed'], w['radiation'], w['evapotrans'],
        lat, lon
    ]])

    if model_xgb is None: model_xgb = joblib.load('uhi_xgb.pkl')
    if model_rf  is None: model_rf  = joblib.load('uhi_rf.pkl')

    uhi = 0.6 * model_xgb.predict(X_input)[0] + 0.4 * model_rf.predict(X_input)[0]

    grade = ('심각' if uhi >= 3 else '높음' if uhi >= 2
             else '중간' if uhi >= 1 else '낮음' if uhi >= 0 else '없음')

    return {
        'lat': lat, 'lon': lon,
        'uhi_index': round(float(uhi), 3),
        'uhi_grade': grade,
        'current_temp': round(w['temp_mean'], 1),
        'estimated_urban_temp': round(w['temp_mean'] + uhi, 1),
    }

