def fetch_weather(lat, lon, days_back=30):
    from datetime import datetime, timedelta
    end   = datetime.now().strftime('%Y-%m-%d')
    start = (datetime.now() - timedelta(days=days_back)).strftime('%Y-%m-%d')

    params = {
        'latitude': lat, 'longitude': lon,
        'hourly': [
            'temperature_2m',
            'relativehumidity_2m',
            'windspeed_10m',
            'shortwave_radiation',
            'et0_fao_evapotranspiration',
            'precipitation',
        ],
        'start_date': start, 'end_date': end,
        'timezone': 'Asia/Seoul'
    }
    try:
        r = openmeteo.weather_api('https://api.open-meteo.com/v1/forecast', params=params)[0].Hourly()
        return {
            'temp_mean':  float(np.nanmean(r.Variables(0).ValuesAsNumpy())),
            'temp_max':   float(np.nanmax(r.Variables(0).ValuesAsNumpy())),
            'humidity':   float(np.nanmean(r.Variables(1).ValuesAsNumpy())),
            'windspeed':  float(np.nanmean(r.Variables(2).ValuesAsNumpy())),
            'radiation':  float(np.nanmean(r.Variables(3).ValuesAsNumpy())),
            'evapotrans': float(np.nanmean(r.Variables(4).ValuesAsNumpy())),
            'precip':     float(np.nansum(r.Variables(5).ValuesAsNumpy())),
        }
    except:
        return None

