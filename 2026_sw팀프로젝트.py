def fetch_weather_realtime(lat, lon):
    params = {
        'latitude': lat, 'longitude': lon,
        'current': [
            'temperature_2m', 'relativehumidity_2m',
            'windspeed_10m',  'shortwave_radiation',
        ],
        'timezone': 'Asia/Seoul'
    }
    r = openmeteo.weather_api('https://api.open-meteo.com/v1/forecast', params=params)[0]
    c = r.Current()
    return {
        'temp_mean':  float(c.Variables(0).Value()),
        'humidity':   float(c.Variables(1).Value()),
        'windspeed':  float(c.Variables(2).Value()),
        'radiation':  float(c.Variables(3).Value()),
        'evapotrans': 0.0,
    }

def uhi_grade(uhi):
    if uhi >= 3: return '심각'
    if uhi >= 2: return '높음'
    if uhi >= 1: return '중간'
    if uhi >= 0: return '낮음'
    return '없음'

